<?php
/**
 * ============================================================================
 *  class Cfe_Assets
 *  ----------------------------------------------------------------------------
 *  Подключение CSS / JS-бандлов React-админки.
 *
 *  •  Регистрируемся на хуке `admin_enqueue_scripts`
 *  •  Загружаем ассеты только на админ-страницах, чей slug содержит
 *     подстроку `cfe-settings` (см. `$hook`, который WP передаёт в колбэк).
 *  •  Файлы расположены в папке  /assets/{css|js}/  относительно корня плагина.
 *    -  admin.css   – глобальные стили админки
 *    -  admin.js    – скомпилированный React-бандл
 * ============================================================================
 */

defined('ABSPATH') or die('Прямой доступ запрещен!');

class Cfe_Assets {
    /* --------------------------------------------------------------------- */
	/* 1. Конструктор: вешаемся на enqueue-хук                              */
	/* --------------------------------------------------------------------- */
    public function __construct() {
        add_action('admin_enqueue_scripts', [$this, 'enqueue_assets']);
    }

    /* --------------------------------------------------------------------- */
	/* 2. Подключаем ассеты (только когда нужно)                             */
	/* --------------------------------------------------------------------- */
    public function enqueue_assets($hook) {
        /*  Если это не наша страница настроек – выходим сразу  */
        if (strpos($hook, 'cfe-settings') === false) {
            return;
        }

        /* ---------------- CSS ---------------- */
        wp_enqueue_style(
            'cfe-admin-css',
            plugins_url('/assets/css/admin.css', dirname(__FILE__) . '../')
        );

        /* ---------------- JS  ---------------- */
        wp_enqueue_script(
            'cfe-admin-js',
            plugins_url('/assets/js/admin.js', dirname(__FILE__) . '../'),
            ['jquery'],
            '1.0',
            true // загружаем в footer
        );
    }
}