/* общий REST-хелпер */
const cfeChangeGroupStatus = (id, target = '') => {
	const query = target ? `?target_status=${target}` : '';
	return wp.apiFetch({
		path   : `${cfeSettings.field_group_status_base}/${id}/status${query}`
		         .replace(window.location.origin, ''),
		method : 'PATCH',
		headers: { 'X-WP-Nonce': cfeSettings.nonce },
	});
};

